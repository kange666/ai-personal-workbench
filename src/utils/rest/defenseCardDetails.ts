export function defenseCardDetails(state: DefenseState, id: string) {
  const stats = defenseStats(state);
  const current = state.cards[id] || 0;
  const context = `当前攻击${stats.damage.toFixed(1)} · 攻速${stats.rate.toFixed(1)}/秒 · 生命上限${Math.round(stats.maxHP)}`;
  return { description: details[id] || DEFENSE_CARDS.find(card => card.id === id)?.description || '', context, current };
}
